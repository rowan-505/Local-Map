-- ---------------------------------------------------------------------------
-- 7) Assertions + anomaly summary notice
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  b record;
  after_lines bigint;
  after_polygons bigint;
  after_line_names bigint;
  after_poly_names bigint;
  null_class_lines bigint;
  null_class_polys bigint;
  orphan_lines bigint;
  orphan_polys bigint;
  anomaly_total bigint;
  anomaly_other bigint;
BEGIN
  SELECT * INTO b FROM _m156_before;
  SELECT count(*) INTO after_lines FROM core.core_water_lines;
  SELECT count(*) INTO after_polygons FROM core.core_water_polygons;
  SELECT count(*) INTO after_line_names FROM core.core_water_line_names;
  SELECT count(*) INTO after_poly_names FROM core.core_water_polygon_names;

  IF b.water_lines IS DISTINCT FROM after_lines THEN
    RAISE EXCEPTION '156: water_lines count changed % → %', b.water_lines, after_lines;
  END IF;
  IF b.water_polygons IS DISTINCT FROM after_polygons THEN
    RAISE EXCEPTION '156: water_polygons count changed % → %', b.water_polygons, after_polygons;
  END IF;
  IF b.water_line_names IS DISTINCT FROM after_line_names THEN
    RAISE EXCEPTION '156: water_line_names count changed';
  END IF;
  IF b.water_polygon_names IS DISTINCT FROM after_poly_names THEN
    RAISE EXCEPTION '156: water_polygon_names count changed';
  END IF;

  SELECT count(*) INTO null_class_lines FROM core.core_water_lines WHERE water_class_id IS NULL;
  SELECT count(*) INTO null_class_polys FROM core.core_water_polygons WHERE water_class_id IS NULL;
  IF null_class_lines > 0 OR null_class_polys > 0 THEN
    RAISE EXCEPTION '156: null water_class_id lines=% polygons=%', null_class_lines, null_class_polys;
  END IF;

  SELECT count(*) INTO orphan_lines
  FROM core.core_water_lines w
  LEFT JOIN ref.ref_water_classes c ON c.id = w.water_class_id
  WHERE c.id IS NULL;
  SELECT count(*) INTO orphan_polys
  FROM core.core_water_polygons w
  LEFT JOIN ref.ref_water_classes c ON c.id = w.water_class_id
  WHERE c.id IS NULL;
  IF orphan_lines > 0 OR orphan_polys > 0 THEN
    RAISE EXCEPTION '156: orphan water_class_id lines=% polygons=%', orphan_lines, orphan_polys;
  END IF;

  SELECT count(*) INTO anomaly_total FROM system.migration_156_water_class_anomalies;
  SELECT count(*) INTO anomaly_other
  FROM system.migration_156_water_class_anomalies WHERE resolved_code = 'other';

  RAISE NOTICE '156 anomaly rows=% (resolved_other=%). See system.migration_156_water_class_anomalies',
    anomaly_total, anomaly_other;
END $$;

COMMIT;

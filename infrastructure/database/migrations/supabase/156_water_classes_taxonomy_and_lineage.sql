WITH raw AS (
  SELECT
    'lines'::text AS kind,
    w.id,
    nullif(btrim(w.source_refs ->> 'osm_id'), '') AS osm_id_text,
    lower(nullif(btrim(w.source_refs ->> 'osm_feature_type'), '')) AS osm_ft,
    nullif(btrim(w.source_refs ->> 'region_code'), '') AS region_code,
    coalesce(
      nullif(btrim(w.source_refs ->> 'source_snapshot_version'), ''),
      nullif(btrim(w.source_refs ->> 'snapshot_version'), '')
    ) AS snapshot_version,
    nullif(btrim(w.external_id), '') AS external_id
  FROM core.core_water_lines w
  UNION ALL
  SELECT
    'polygons',
    w.id,
    nullif(btrim(w.source_refs ->> 'osm_id'), ''),
    lower(nullif(btrim(w.source_refs ->> 'osm_feature_type'), '')),
    nullif(btrim(w.source_refs ->> 'region_code'), ''),
    coalesce(
      nullif(btrim(w.source_refs ->> 'source_snapshot_version'), ''),
      nullif(btrim(w.source_refs ->> 'snapshot_version'), '')
    ),
    nullif(btrim(w.external_id), '')
  FROM core.core_water_polygons w
),
parsed AS (
  SELECT
    r.*,
    CASE
      WHEN r.osm_id_text ~ '^[1-9][0-9]*$'
        OR r.external_id ~* '^osm:(way|relation|node|w|r|n):'
        THEN 'osm_myanmar'
      ELSE NULL
    END AS source_code,
    CASE
      WHEN r.osm_ft IN ('w','way') THEN 'way'
      WHEN r.osm_ft IN ('r','rel','relation') THEN 'relation'
      WHEN r.osm_ft IN ('n','node') THEN 'node'
      WHEN r.external_id ~* '^osm:(way|w):' THEN 'way'
      WHEN r.external_id ~* '^osm:(relation|r):' THEN 'relation'
      WHEN r.external_id ~* '^osm:(node|n):' THEN 'node'
      ELSE NULL
    END AS source_feature_type,
    CASE
      WHEN r.osm_id_text ~ '^[1-9][0-9]*$'
       AND r.osm_id_text::numeric <= 9223372036854775807::numeric
        THEN r.osm_id_text::bigint
      WHEN r.external_id ~* '^osm:(way|relation|node|w|r|n):([1-9][0-9]*)$'
        THEN (regexp_match(r.external_id, '([1-9][0-9]*)$'))[1]::bigint
      ELSE NULL
    END AS source_feature_id,
    lower(nullif(btrim(r.region_code), '')) AS region_norm
  FROM raw r
)
UPDATE core.core_water_lines AS w
SET
  source_registry_id = COALESCE(w.source_registry_id, reg.id),
  source_snapshot_id = COALESCE(w.source_snapshot_id, snap.id),

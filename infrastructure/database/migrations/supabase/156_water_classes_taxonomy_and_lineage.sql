CREATE TEMP TABLE _m156_resolve ON COMMIT DROP AS
WITH src AS (
  SELECT
    'core.core_water_lines'::text AS entity_table,
    w.id,
    lower(nullif(btrim(w.class_code), '')) AS legacy_code,
    lower(nullif(btrim(w.normalized_data #>> '{tags,waterway}'), '')) AS tag_waterway,
    lower(nullif(btrim(w.normalized_data #>> '{tags,water}'), '')) AS tag_water,
    lower(nullif(btrim(w.normalized_data #>> '{tags,natural}'), '')) AS tag_natural,
    lower(nullif(btrim(w.normalized_data #>> '{waterway}'), '')) AS nd_waterway,
    lower(nullif(btrim(w.normalized_data #>> '{water}'), '')) AS nd_water
  FROM core.core_water_lines w
  UNION ALL
  SELECT
    'core.core_water_polygons',
    w.id,
    lower(nullif(btrim(w.class_code), '')),
    lower(nullif(btrim(w.normalized_data #>> '{tags,waterway}'), '')),
    lower(nullif(btrim(w.normalized_data #>> '{tags,water}'), '')),
    lower(nullif(btrim(w.normalized_data #>> '{tags,natural}'), '')),
    lower(nullif(btrim(w.normalized_data #>> '{waterway}'), '')),
    lower(nullif(btrim(w.normalized_data #>> '{water}'), ''))
  FROM core.core_water_polygons w
),
norm AS (
  SELECT
    s.*,
    -- Prefer OSM tags when present; fall back to legacy class_code.
    coalesce(
      nullif(s.tag_waterway, ''),
      nullif(s.nd_waterway, ''),
      nullif(s.tag_water, ''),
      nullif(s.nd_water, ''),
      s.legacy_code
    ) AS primary_hint,
    coalesce(nullif(s.tag_water, ''), nullif(s.nd_water, ''), s.legacy_code) AS water_hint
  FROM src s
),
mapped AS (
  SELECT
    n.*,
    CASE
      -- Invalid / property-like values → other (anomaly)
      WHEN n.primary_hint IN ('yes', 'seasonal', 'intermittent', 'eris', 'pressurised')
        OR n.legacy_code IN ('yes', 'seasonal', 'intermittent', 'eris', 'pressurised')
        THEN 'other'
      WHEN n.primary_hint = 'lake;pond' OR n.legacy_code = 'lake;pond'
        THEN 'lake'
      WHEN n.primary_hint IN ('fish farming pond', 'fish_farming_pond')
        OR n.legacy_code IN ('fish farming pond', 'fish_farming_pond')
        THEN 'fishpond'
      WHEN n.primary_hint IN ('pool', 'small_water_hole')
        OR n.legacy_code IN ('pool', 'small_water_hole')
        THEN CASE
          WHEN n.entity_table = 'core.core_water_lines' THEN 'stream_pool'
          ELSE 'pond'
        END
      WHEN n.primary_hint = 'fish_pass' OR n.legacy_code = 'fish_pass'
        THEN 'other'
      -- Canonical leaf codes
      WHEN n.primary_hint IN (
        'river','stream','canal','tidal_channel','ditch','drain',
        'water','lake','reservoir','pond','basin','lagoon','oxbow','fishpond','moat','stream_pool','wastewater',
        'dam','weir','lock','lock_gate','sluice_gate','waterfall','dock','boatyard'
      ) THEN n.primary_hint
      WHEN n.water_hint IN (
        'river','stream','canal','tidal_channel','ditch','drain',
        'water','lake','reservoir','pond','basin','lagoon','oxbow','fishpond','moat','stream_pool','wastewater',
        'dam','weir','lock','lock_gate','sluice_gate','waterfall','dock','boatyard'
      ) THEN n.water_hint
      WHEN n.tag_natural = 'water' AND n.water_hint IS NULL AND n.primary_hint IS NULL
        THEN 'water'
      ELSE 'other'
    END AS resolved_code,
    CASE
      WHEN n.primary_hint IN ('yes', 'seasonal', 'intermittent', 'eris', 'pressurised')
        OR n.legacy_code IN ('yes', 'seasonal', 'intermittent', 'eris', 'pressurised')
        THEN 'invalid_or_property_value'
      WHEN n.primary_hint = 'lake;pond' OR n.legacy_code = 'lake;pond'
        THEN 'compound_value_normalized_to_lake'
      WHEN n.primary_hint IN ('fish farming pond', 'fish_farming_pond', 'pool', 'small_water_hole', 'fish_pass')
        OR n.legacy_code IN ('fish farming pond', 'fish_farming_pond', 'pool', 'small_water_hole', 'fish_pass')
        THEN 'alias_normalized'
      WHEN n.primary_hint IN (
        'river','stream','canal','tidal_channel','ditch','drain',
        'water','lake','reservoir','pond','basin','lagoon','oxbow','fishpond','moat','stream_pool','wastewater',
        'dam','weir','lock','lock_gate','sluice_gate','waterfall','dock','boatyard'
      ) OR n.water_hint IN (
        'river','stream','canal','tidal_channel','ditch','drain',
        'water','lake','reservoir','pond','basin','lagoon','oxbow','fishpond','moat','stream_pool','wastewater',
        'dam','weir','lock','lock_gate','sluice_gate','waterfall','dock','boatyard'
      )
        THEN 'canonical'
      ELSE 'unresolved_fallback_other'
    END AS reason
  FROM norm n
)
SELECT * FROM mapped;


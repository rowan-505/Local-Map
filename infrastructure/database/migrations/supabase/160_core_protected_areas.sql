-- =============================================================================
-- Supabase migration 160: protected-area overlay (schema only)
-- =============================================================================
--
-- Protected areas are a legal/management overlay — NOT land cover and NOT
-- ordinary parks. They may overlap forest, wetland, grassland, water, etc.
--
-- Creates:
--   ref.ref_protected_area_classes
--   core.core_protected_areas
--   core.core_protected_area_names
--   import_review.protected_area_candidates
--   tiles.tiles_protected_areas_v
--   search.v_search_protected_areas_source  (named active only)
--
-- Does NOT:
--   import national protected-area OSM data
--   migrate existing nature_reserve / park rows out of core_land_areas
--   rebuild PMTiles / wire search rebuild defaults
--   create separate national_park / nature_reserve / forest_reserve tables
-- =============================================================================


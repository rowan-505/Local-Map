-- ---------------------------------------------------------------------------
-- 5) Tile view (classification from ref FK; no PMTiles rebuild)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW tiles.tiles_protected_areas_v AS
SELECT
  p.id,
  p.public_id,
  pc.name_en AS protected_area_class,
  pc.code AS protected_area_class_code,
  COALESCE(nm.name_en, nm.name_my, nm.name_und) AS name,
  p.geom
FROM core.core_protected_areas AS p
INNER JOIN ref.ref_protected_area_classes AS pc
  ON pc.id = p.protected_area_class_id
LEFT JOIN LATERAL (
  SELECT
    (SELECT x.name FROM core.core_protected_area_names x
      WHERE x.protected_area_id = p.id
        AND x.language_code = 'en'
      ORDER BY CASE WHEN x.is_primary THEN 0 ELSE 1 END, x.search_weight DESC NULLS LAST, x.name
      LIMIT 1) AS name_en,
    (SELECT x.name FROM core.core_protected_area_names x
      WHERE x.protected_area_id = p.id
        AND x.language_code = 'my'
      ORDER BY CASE WHEN x.is_primary THEN 0 ELSE 1 END, x.search_weight DESC NULLS LAST, x.name
      LIMIT 1) AS name_my,
    (SELECT x.name FROM core.core_protected_area_names x
      WHERE x.protected_area_id = p.id
        AND x.language_code = 'und'
      ORDER BY CASE WHEN x.is_primary THEN 0 ELSE 1 END, x.search_weight DESC NULLS LAST, x.name
      LIMIT 1) AS name_und
) nm ON true
WHERE p.is_active IS TRUE
  AND p.deleted_at IS NULL
  AND p.geom IS NOT NULL
  AND NOT ST_IsEmpty(p.geom);

COMMENT ON VIEW tiles.tiles_protected_areas_v IS
  'Protected-area overlay for MVT. Class from ref.ref_protected_area_classes via protected_area_class_id. '
  'Not wired into production PMTiles build yet.';

REVOKE ALL ON TABLE tiles.tiles_protected_areas_v FROM PUBLIC;

-- ---------------------------------------------------------------------------
-- 6) Search source — named active rows only (not wired into rebuild defaults)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW search.v_search_protected_areas_source AS
SELECT
  'protected_area'::text AS entity_type,
  p.id AS entity_id,
  p.public_id::text AS public_id,
  COALESCE(nm.name_en, nm.name_my, nm.name_und, pc.name_en) AS display_name,
  pc.name_en AS subtitle,
  COALESCE(nm.name_my, nm.name_und) AS primary_name_my,
  COALESCE(nm.name_en, nm.name_und) AS primary_name_en,
  COALESCE(nm.name_und, nm.name_en, nm.name_my) AS primary_name_und,
  pc.code AS code,
  p.external_id,
  pc.code AS category_code,
  pc.name_mm AS category_name_my,
  pc.name_en AS category_name_en,
  p.admin_area_id,
  ctx.adm_my AS admin_area_name_my,
  ctx.adm_en AS admin_area_name_en,
  ctx.hierarchy AS admin_hierarchy,
  NULL::text AS address_text,
  NULL::jsonb AS address_parts,
  geometrytype(p.geom) AS geometry_type,
  COALESCE(p.centroid, search.safe_centroid(p.geom)) AS centroid,
  search.safe_bbox(p.geom) AS bbox,
  (COALESCE(p.centroid, search.safe_centroid(p.geom)) IS NOT NULL) AS has_geometry,
  (COALESCE(p.centroid, search.safe_centroid(p.geom)) IS NOT NULL) AS supports_plus_code,
  concat_ws(
    ' ',
    nm.all_names, pc.name_en, pc.name_mm, pc.code,
    ctx.adm_en, ctx.adm_my, search.hierarchy_text(ctx.hierarchy)
  ) AS searchable_text,
  0::numeric AS importance_score,
  0::numeric AS popularity_score,
  COALESCE(p.confidence_score, 0) AS confidence_score,
  0::numeric AS boundary_confidence_score,
  COALESCE(p.is_verified, false) AS is_verified,
  true AS is_public,
  COALESCE(p.is_active, false) AS is_active,
  p.updated_at AS source_updated_at,
  COALESCE(nm.names_json, '[]'::jsonb) AS names
FROM core.core_protected_areas AS p
INNER JOIN ref.ref_protected_area_classes AS pc
  ON pc.id = p.protected_area_class_id
LEFT JOIN LATERAL (
  SELECT
    search.admin_area_name(p.admin_area_id, 'my') AS adm_my,
    search.admin_area_name(p.admin_area_id, 'en') AS adm_en,
    search.admin_area_hierarchy(p.admin_area_id) AS hierarchy
) ctx ON true
LEFT JOIN LATERAL (
  SELECT
    (SELECT x.name FROM core.core_protected_area_names x
      WHERE x.protected_area_id = p.id
        AND (x.language_code = 'my' OR upper(trim(coalesce(x.script_code, ''))) = 'MYMR')
      ORDER BY CASE WHEN x.name_type = 'official' AND x.is_primary THEN 1
                    WHEN x.is_primary THEN 2
                    WHEN x.name_type = 'official' THEN 3 ELSE 4 END,
               x.search_weight DESC NULLS LAST, x.name
      LIMIT 1) AS name_my,
    (SELECT x.name FROM core.core_protected_area_names x
      WHERE x.protected_area_id = p.id
        AND (x.language_code = 'en' OR upper(trim(coalesce(x.script_code, ''))) = 'LATN')
      ORDER BY CASE WHEN x.name_type = 'official' AND x.is_primary THEN 1
                    WHEN x.is_primary THEN 2
                    WHEN x.name_type = 'official' THEN 3 ELSE 4 END,
               x.search_weight DESC NULLS LAST, x.name
      LIMIT 1) AS name_en,
    (SELECT x.name FROM core.core_protected_area_names x
      WHERE x.protected_area_id = p.id AND x.language_code = 'und'
      ORDER BY CASE WHEN x.is_primary THEN 1 ELSE 2 END,
               x.search_weight DESC NULLS LAST, x.name
      LIMIT 1) AS name_und,
    (SELECT jsonb_agg(jsonb_build_object(
              'name', x.name, 'language_code', x.language_code,
              'script_code', x.script_code, 'name_type', x.name_type,
              'is_primary', x.is_primary, 'search_weight', coalesce(x.search_weight, 0))
              ORDER BY x.is_primary DESC, x.name)
        FROM core.core_protected_area_names x
        WHERE x.protected_area_id = p.id) AS names_json,
    (SELECT string_agg(DISTINCT x.name, ' ')
        FROM core.core_protected_area_names x
        WHERE x.protected_area_id = p.id) AS all_names
) nm ON true
WHERE p.deleted_at IS NULL
  AND p.is_active IS TRUE
  AND p.geom IS NOT NULL
  AND NOT ST_IsEmpty(p.geom)
  AND EXISTS (
    SELECT 1
    FROM core.core_protected_area_names x
    WHERE x.protected_area_id = p.id
      AND nullif(btrim(x.name), '') IS NOT NULL
  );

COMMENT ON VIEW search.v_search_protected_areas_source IS
  'Search source for named active protected areas only (entity_type=protected_area). '
  'Not added to default search rebuild list in this migration.';

-- ---------------------------------------------------------------------------
-- 7) Assertions
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  before_land bigint;
  before_names bigint;
  after_land bigint;
  after_names bigint;
  class_count bigint;
  dup_code bigint;
  core_rows bigint;
  name_rows bigint;
  ir_rows bigint;
BEGIN
  SELECT land_areas, land_area_names INTO before_land, before_names FROM _m160_before;
  SELECT count(*) INTO after_land FROM core.core_land_areas;
  SELECT count(*) INTO after_names FROM core.core_land_area_names;

  IF after_land IS DISTINCT FROM before_land THEN
    RAISE EXCEPTION '160: core_land_areas count changed % → %', before_land, after_land;
  END IF;
  IF after_names IS DISTINCT FROM before_names THEN
    RAISE EXCEPTION '160: core_land_area_names count changed % → %', before_names, after_names;
  END IF;

  SELECT count(*) INTO class_count FROM ref.ref_protected_area_classes WHERE is_active;
  IF class_count < 6 THEN
    RAISE EXCEPTION '160: expected >=6 active protected area classes, got %', class_count;
  END IF;

  SELECT count(*) INTO dup_code
  FROM (
    SELECT lower(btrim(code)) FROM ref.ref_protected_area_classes GROUP BY 1 HAVING count(*) > 1
  ) d;
  IF dup_code <> 0 THEN
    RAISE EXCEPTION '160: duplicate protected area class codes = %', dup_code;
  END IF;

  IF to_regclass('core.core_protected_areas') IS NULL
     OR to_regclass('core.core_protected_area_names') IS NULL
     OR to_regclass('ref.ref_protected_area_classes') IS NULL
     OR to_regclass('import_review.protected_area_candidates') IS NULL
     OR to_regclass('tiles.tiles_protected_areas_v') IS NULL
     OR to_regclass('search.v_search_protected_areas_source') IS NULL THEN
    RAISE EXCEPTION '160: required objects missing';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM ref.ref_protected_area_classes
    WHERE code IN (
      'national_park', 'nature_reserve', 'wildlife_protected_area',
      'forest_reserve', 'marine_protected_area', 'other'
    )
    HAVING count(*) = 6
  ) THEN
    RAISE EXCEPTION '160: required class codes missing';
  END IF;

  SELECT count(*) INTO core_rows FROM core.core_protected_areas;
  SELECT count(*) INTO name_rows FROM core.core_protected_area_names;
  SELECT count(*) INTO ir_rows FROM import_review.protected_area_candidates;
  IF core_rows <> 0 OR name_rows <> 0 OR ir_rows <> 0 THEN
    RAISE EXCEPTION '160: expected empty protected-area tables (no import yet); got core=% names=% ir=%',
      core_rows, name_rows, ir_rows;
  END IF;

  IF pg_get_viewdef('tiles.tiles_protected_areas_v'::regclass, true)
       NOT ILIKE '%ref.ref_protected_area_classes%' THEN
    RAISE EXCEPTION '160: tiles view does not join ref.ref_protected_area_classes';
  END IF;

  RAISE NOTICE '160 ok: land_areas=% classes=% (schema only, zero protected rows)',
    after_land, class_count;
END $$;

COMMIT;

    BEGIN
        REVOKE ALL ON TABLE import_work.road_rows
            FROM anon, authenticated, authenticator, service_role;
    EXCEPTION
        WHEN undefined_object THEN
            NULL;
    END;
    ALTER TABLE import_work.road_rows ENABLE ROW LEVEL SECURITY;
END $$;

COMMIT;
